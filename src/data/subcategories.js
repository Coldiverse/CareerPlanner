// Helper to get subcategories for a subject
export const getSubcategoriesBySubject = (subjectId) => {
  return SUBCATEGORIES.filter(sc => sc.parentSubjectId === subjectId);
};

// Helper to get a single subcategory by ID
export const getSubcategoryById = (subcategoryId) => {
  return SUBCATEGORIES.find(sc => sc.id === subcategoryId);
};
