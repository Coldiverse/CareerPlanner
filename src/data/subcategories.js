// Helper to get subcategories for a subject
export const getSubcategoriesBySubject = (subjectId) => {
  return SUBCATEGORIES.filter(sc => sc.parentSubjectId === subjectId);
};

// Helper to get a single subcategory by ID
export const getSubcategoryById = (subcategoryId) => {
  return SUBCATEGORIES.find(sc => sc.id === subcategoryId);
};

// Helper to search subcategories by name or description
export const searchSubcategories = (query) => {
  const lowerQuery = query.toLowerCase();
  return SUBCATEGORIES.filter(sc =>
    sc.name.toLowerCase().includes(lowerQuery) ||
    sc.description.toLowerCase().includes(lowerQuery) ||
    sc.parentSubjectName.toLowerCase().includes(lowerQuery)
  );
};
